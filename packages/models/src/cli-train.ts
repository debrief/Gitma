// tma-train. This module must not import tfjs-node (directly or through ./train.js) at load time:
// the config's tfjs_threads is applied to the environment first, and only then is the trainer
// imported, so libtensorflow creates its thread pools with that size (see threads.ts).
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";
import { canonicalJson, isMain, UsageError } from "@tma/data";
import { openFeatures } from "@tma/features";
import { ModelManifest, parseRecord, RecordError, TrainingConfig } from "@tma/types";
import { runAsyncCli } from "./cli-run.js";
import { g0Accepted, generatorPathsEqual } from "./g0-guard.js";
import { checkLineage } from "./lineage.js";
import { sha256File } from "./manifest.js";
import { applyThreads, threadSettings } from "./threads.js";

/** Git checks, injectable for tests (defaults run git in this checkout). */
export interface TrainDeps {
  /** Generator paths in the working tree equal those at `commit` (G0 guard). */
  generatorUnchanged?: (commit: string) => boolean;
  /** Generator paths equal at two commits (lineage). */
  generatorPathsEqual?: (a: string, b: string) => boolean;
}

/**
 * A completed continuation's kept weights must be explained by its record (schema 0.8.2; G2 2b
 * panel, red team round 2): a best epoch after the source's has best_val_loss equal to that
 * epoch's val_loss; the source's own best epoch kept means best_val_loss equals the re-scored
 * value and the weights are the source's.
 */
export function checkContinuation(m: ModelManifest, path: string): void {
  const c = m.continued_from;
  if (c == null || !m.complete) return;
  const lineage = (msg: string): never => {
    throw new RecordError(path, "lineage", msg);
  };
  if (m.best_val_loss == null) lineage("a continuation must record best_val_loss");
  if (m.best_epoch > c.best_epoch) {
    const kept = m.epochs.find((e) => e.epoch === m.best_epoch)?.val_loss;
    if (kept !== m.best_val_loss) {
      lineage(
        `best_val_loss ${String(m.best_val_loss)} is not best epoch ${String(m.best_epoch)}'s val_loss ${String(kept)}`,
      );
    }
  } else {
    if (m.best_epoch !== c.best_epoch) lineage("best_epoch precedes the continuation's source");
    if (c.rescored_val_loss == null || m.best_val_loss !== c.rescored_val_loss) {
      lineage(
        `the source's weights were kept, so best_val_loss ${String(m.best_val_loss)} must be the re-scored value ${String(c.rescored_val_loss)}`,
      );
    }
    if (m.weights_digest !== c.weights_digest) {
      lineage("the source's best epoch was kept but the weights differ from the source's");
    }
  }
}

export async function main(argv: string[], deps: TrainDeps = {}): Promise<unknown> {
  const { values } = parseArgs({
    args: argv,
    strict: true,
    options: {
      config: { type: "string" },
      train: { type: "string" },
      val: { type: "string" },
      out: { type: "string" },
      experiments: { type: "string", default: "experiments" },
      check: { type: "boolean", default: false },
      "allow-unreviewed-g0": { type: "boolean", default: false },
    },
  });
  if (!values.config || !values.train || !values.val || !values.out) {
    throw new UsageError(
      "usage: tma-train --config <config.json> --train <train.features.bin> --val <validation.features.bin> --out <dir> [--experiments dir] [--check] [--allow-unreviewed-g0]",
    );
  }
  const g0 = g0Accepted(values.experiments, {
    requireReview: !values["allow-unreviewed-g0"],
    ...(deps.generatorUnchanged === undefined
      ? {}
      : { generatorUnchanged: deps.generatorUnchanged }),
  });
  if (g0 === null) {
    throw new RecordError(
      values.experiments,
      "G0",
      "no passing, panel-decided G0 verdict: training is not allowed (constitution V)",
    );
  }
  const config = parseRecord(
    TrainingConfig,
    JSON.parse(readFileSync(values.config, "utf8")),
    values.config,
    "config",
  );
  // Lineage (research R2): both files from one clean dataset generated by the G0-verified code.
  const trainFile = openFeatures(values.train);
  const valFile = openFeatures(values.val);
  try {
    checkLineage({
      train: trainFile,
      val: valFile,
      config,
      g0Commit: g0.commit,
      generatorPathsEqual: deps.generatorPathsEqual ?? generatorPathsEqual,
    });
  } finally {
    trainFile.close();
    valFile.close();
  }
  // --check: the G0 guard and lineage only (CI runs it before skipping a model whose checkpoint
  // is already complete, so a no-op job still refuses data the guard would refuse).
  if (values.check) {
    // A model already complete in --out must have trained on these very files: a checkpoint left
    // from another plan or dataset is refused, not reused (G0 panel red team, round 2).
    const manifestPath = join(values.out, "manifest.json");
    if (existsSync(manifestPath)) {
      const prior = parseRecord(
        ModelManifest,
        JSON.parse(readFileSync(manifestPath, "utf8")),
        manifestPath,
        "manifest",
      );
      // Streamed: derived phase-4 features exceed readFileSync's 2 GiB limit (train/p4b job 2).
      const now = { train: sha256File(values.train), val: sha256File(values.val) };
      if (canonicalJson(prior.config) !== canonicalJson(config)) {
        throw new RecordError(
          manifestPath,
          "lineage",
          "the model in --out was trained with another config; it is not this plan's model",
        );
      }
      if (prior.train_features_digest !== now.train || prior.val_features_digest !== now.val) {
        throw new RecordError(
          manifestPath,
          "lineage",
          `checkpoint trained on train ${prior.train_features_digest} / validation ${prior.val_features_digest}, these files are ${now.train} / ${now.val}`,
        );
      }
      checkContinuation(prior, manifestPath);
    }
    return { id: config.id, g0_experiment: g0.id, check: "pass" };
  }
  if (config.tfjs_threads !== undefined && config.tfjs_threads !== null) {
    applyThreads(config.tfjs_threads);
  }
  const { train } = await import("./train.js");
  const m = await train({
    config,
    trainPath: values.train,
    valPath: values.val,
    outDir: values.out,
    g0Experiment: g0.id,
  });
  if (m.stop_reason === "diverged") throw new Error(`${config.id}: training diverged`);
  return {
    id: m.id,
    g0_experiment: g0.id,
    stop_reason: m.stop_reason,
    best_epoch: m.best_epoch,
    epochs: m.epochs.length,
    wall_s: Math.round(m.wall_s),
    ...threadSettings(),
  };
}

if (isMain(import.meta.url)) runAsyncCli((argv) => main(argv), process.argv.slice(2));
